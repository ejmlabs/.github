#!/usr/bin/env node
// Builds web/site.css from the ordered parts in web/parts/. Each concern owns one part:
//   10-base    page shell, patterns and layout
//   20-dark    dark theme
//   30-motion  animation and transitions
//   40-responsive  very small and very large screens
//   50-demo    interactive product demos
// Edit a part, then run node scripts/build-web.mjs. Never edit web/site.css by hand.
// Usage: node scripts/build-web.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..', 'web');
const parts = readdirSync(join(web, 'parts')).filter(f => /^\d+-.+\.css$/.test(f)).sort();
const banner = `/* Generated by scripts/build-web.mjs from web/parts/ (${parts.join(', ')}). Do not edit by hand.
   Load in this order: ../tokens/brand.css, ../components/brand-components.css, this file.
   Motif and icon URLs are relative to this file, so keep the design-kit folder together. */
@import url('../ui/theme.css');
`;
const out = banner + parts.map(f => `\n/* ---- ${f} ---- */\n${readFileSync(join(web, 'parts', f), 'utf8').trimEnd()}\n`).join('');
const target = join(web, 'site.css');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('stale: web/site.css (run node scripts/build-web.mjs)'); process.exit(1); }
  console.log(`web/site.css is current (${parts.length} parts)`);
} else {
  writeFileSync(target, out);
  console.log(`wrote web/site.css from ${parts.length} part(s)`);
}
